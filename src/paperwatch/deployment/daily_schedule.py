"""The permanent daily schedule ([setup] daily_schedule = true) and the optional monitor service, as systemd units.

Daily schedule, every day in report.timezone:
  paperwatch-collect.timer    at each schedule.collect_times -> paperwatch-collect.service (`collect`, collector
                              account); a collection missed while the machine was off runs once at boot (Persistent=)
  paperwatch-worker.service   `work`, always running (started at boot and by every collect)
  paperwatch-report.timer     at report.publish_time + REPORT_START_DELAY -> paperwatch-report.service (`report`,
                              no --date: the latest due date). It stops the worker first (Conflicts=) so the writer
                              gets the model at once, retries every 5 minutes on failure, and starts the worker
                              again when it ends (OnSuccess= / OnFailure=).
Mode `hardened`: system units with the service accounts and the same sandbox as the pilot (systemd_units.py).
Mode `local`: user units of the operator (systemctl --user), running the repository's own paperwatch.

The monitor (`[setup] monitor_service = true`) is always a user unit of the operator: it only reads, through the
operator's membership in the shared state group.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timedelta
from pathlib import Path

from paperwatch.config import AppConfig, load_app_config
from paperwatch.deployment.systemd_units import worker_sandbox_lines
from paperwatch.deployment.unit_names import (DAILY_COLLECT_SERVICE, DAILY_COLLECT_TIMER, DAILY_REPORT_SERVICE,
                                              DAILY_REPORT_TIMER, DAILY_WORKER_SERVICE, MONITOR_SERVICE)
from paperwatch.reporting.report_schedule import parse_clock_time

SCOPE_SYSTEM, SCOPE_USER = "system", "user"
REPORT_START_DELAY = timedelta(seconds=30)
REPORT_TIMEOUT = timedelta(minutes=50)
REPORT_RETRY_DELAY_SECONDS = 300
REPORT_MAXIMUM_STARTS_PER_HOUR = 8
COLLECT_TIMEOUT = timedelta(hours=2)
NOTICE = ("# paperwatch daily schedule. Generated by ./setup.sh from settings/paperwatch.toml; edit that file and\n"
          "# re-run ./setup.sh instead of this unit ([setup] daily_schedule = false removes it).\n")


def daily_calendar_time(clock_text: str, timezone_name: str, delay: timedelta = timedelta()) -> str:
    """'*-*-* 06:30:00 America/New_York': every day at that local time."""
    moment = datetime.combine(datetime(2000, 1, 1).date(), parse_clock_time(clock_text)) + delay
    return f"*-*-* {moment:%H:%M:%S} {timezone_name}"


def _command(executable: Path, home: Path, *arguments: str) -> str:
    return " ".join([str(executable), "--home", str(home), *arguments])


def render_daily_units(app_config: AppConfig, *, scope: str, paperwatch_executable: Path,
                       collector_uid: int | None = None) -> dict[str, str]:
    """{unit file name: content}. `collector_uid` (system scope) locates rootless Podman's runtime directory."""
    home, timezone_name = app_config.home_dir, app_config.report.timezone
    if scope == SCOPE_SYSTEM:
        collect_identity = (f"User={app_config.access.collector_account}\nGroup={app_config.access.collector_account}\n"
                            f"SupplementaryGroups={app_config.access.shared_state_group}\nUMask=0007\n"
                            "WorkingDirectory=/\n"
                            f"Environment=XDG_RUNTIME_DIR=/run/user/{collector_uid}\nProtectSystem=full\n")
        worker_identity = worker_sandbox_lines(worker_account=app_config.access.worker_account,
                                               shared_state_group=app_config.access.shared_state_group,
                                               state_dir=app_config.state_dir, output_dir=app_config.output_dir)
        boot_target = "multi-user.target"
    else:
        collect_identity = "UMask=0077\nNoNewPrivileges=yes\n"
        worker_identity = "UMask=0077\nNoNewPrivileges=yes\n"
        boot_target = "default.target"
    collect_calendar_lines = "\n".join(f"OnCalendar={daily_calendar_time(clock_text, timezone_name)}"
                                       for clock_text in app_config.schedule.collect_times)
    return {
        DAILY_COLLECT_SERVICE: f"""{NOTICE}
[Unit]
Description=paperwatch: collect papers (daily schedule)
Wants={DAILY_WORKER_SERVICE}

[Service]
Type=oneshot
{collect_identity}ExecStart={_command(paperwatch_executable, home, "collect")}
TimeoutStartSec={int(COLLECT_TIMEOUT.total_seconds())}
Nice=10
""",
        DAILY_COLLECT_TIMER: f"""{NOTICE}
[Unit]
Description=paperwatch: collection times ({", ".join(app_config.schedule.collect_times)} {timezone_name})

[Timer]
{collect_calendar_lines}
AccuracySec=1s
Persistent=true
Unit={DAILY_COLLECT_SERVICE}

[Install]
WantedBy=timers.target
""",
        DAILY_WORKER_SERVICE: f"""{NOTICE}
[Unit]
Description=paperwatch: worker (reads queued papers with the local model)

[Service]
Type=simple
{worker_identity}ExecStart={_command(paperwatch_executable, home, "work")}
Restart=on-failure
RestartSec=60
# SIGTERM aborts a model call at once and puts the job back in the queue without using an attempt (it resumes from
# its saved stages); this timeout is only the backstop if that ever hangs.
TimeoutStopSec=60

[Install]
WantedBy={boot_target}
""",
        DAILY_REPORT_SERVICE: f"""{NOTICE}
[Unit]
Description=paperwatch: publish the daily report
# Starting the report stops the worker first, so the writer gets the model at once; the worker starts again after.
Conflicts={DAILY_WORKER_SERVICE}
After={DAILY_WORKER_SERVICE}
OnSuccess={DAILY_WORKER_SERVICE}
OnFailure={DAILY_WORKER_SERVICE}
StartLimitIntervalSec=3600
StartLimitBurst={REPORT_MAXIMUM_STARTS_PER_HOUR}

[Service]
Type=oneshot
{worker_identity}ExecStart={_command(paperwatch_executable, home, "report")}
TimeoutStartSec={int(REPORT_TIMEOUT.total_seconds())}
Restart=on-failure
RestartSec={REPORT_RETRY_DELAY_SECONDS}
""",
        DAILY_REPORT_TIMER: f"""{NOTICE}
[Unit]
Description=paperwatch: report time ({app_config.report.publish_time} {timezone_name})

[Timer]
OnCalendar={daily_calendar_time(app_config.report.publish_time, timezone_name, REPORT_START_DELAY)}
AccuracySec=1s
Persistent=true
Unit={DAILY_REPORT_SERVICE}

[Install]
WantedBy=timers.target
""",
    }


def render_monitor_unit(app_config: AppConfig, *, paperwatch_executable: Path, port: int,
                        listen_address: str) -> str:
    return f"""{NOTICE}
[Unit]
Description=paperwatch monitor (read-only web page on {listen_address}:{port})

[Service]
Type=simple
ExecStart={_command(paperwatch_executable, app_config.home_dir, "monitor", "--port", str(port),
                    "--listen-address", listen_address)}
Restart=on-failure
RestartSec=30
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the daily schedule's or the monitor's systemd units.")
    parser.add_argument("what", choices=("daily", "monitor"))
    parser.add_argument("--home", type=Path, required=True)
    parser.add_argument("--unit-dir", type=Path, required=True)
    parser.add_argument("--scope", choices=(SCOPE_SYSTEM, SCOPE_USER), default=SCOPE_SYSTEM)
    parser.add_argument("--paperwatch-executable", type=Path, required=True)
    parser.add_argument("--collector-uid", type=int, default=None)
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--listen-address", default="127.0.0.1")
    arguments = parser.parse_args(argv)
    app_config = load_app_config(arguments.home)
    if arguments.what == "daily":
        if arguments.scope == SCOPE_SYSTEM and arguments.collector_uid is None:
            parser.error("--collector-uid is required for system units")
        units = render_daily_units(app_config, scope=arguments.scope,
                                   paperwatch_executable=arguments.paperwatch_executable,
                                   collector_uid=arguments.collector_uid)
    else:
        units = {MONITOR_SERVICE: render_monitor_unit(app_config, paperwatch_executable=arguments.paperwatch_executable,
                                                      port=arguments.port, listen_address=arguments.listen_address)}
    arguments.unit_dir.mkdir(parents=True, exist_ok=True)
    for unit_name, unit_text in units.items():
        unit_path = arguments.unit_dir / unit_name
        unit_path.write_text(unit_text, encoding="utf-8")
        unit_path.chmod(0o644)
        print(f"rendered {unit_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
